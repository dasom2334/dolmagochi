// ── 벽 한 장 — 유리 구멍만 뚫림. 창틀은 웜 우드(레퍼런스) ──
function wall() {
  const W = 128, H = 49;
  const glass = new Set();
  for (const [x0, y0, x1, y1] of BD_GLASS)
    for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) glass.add(y * 1000 + x);
  const cell = new Map();
  const put = (x, y, c) => {
    if (y < 0 || y >= H || x < 0 || x >= W || glass.has(y * 1000 + x)) return;
    cell.set(y * 1000 + x, c);
  };
  for (let y = 0; y < H; y++)
    for (let x = 0; x < W; x++) {
      const r = h2(x, y, 200);
      put(x, y, r < 8 ? '#332e40' : r > 93 ? '#423c54' : '#3a3448');
    }
  for (let x = 0; x < W; x++) { put(x, 47, '#4b4360'); put(x, 48, '#2b2637'); }
  for (let x = 19; x <= 57; x++) { put(x, 5, WH); put(x, 6, WD); }
  for (let y = 5; y <= 31; y++) {
    put(19, y, WT); put(20, y, WM); put(21, y, WD);
    put(55, y, WD); put(56, y, WM); put(57, y, WT);
  }
  for (let y = 7; y <= 31; y++) put(37, y, WM);
  for (let x = 22; x <= 54; x++) put(x, 18, WM);
  // 창턱 없음(지적) — 틀 하단 마감 2행만: 프레임 띠 + 밑 그늘
  for (let x = 19; x <= 57; x++) put(x, 32, WT);
  for (let x = 19; x <= 57; x++) put(x, 33, WD);
  const rects = emitRows([...cell].map(([k, c]) => [Math.floor(k / 1000), k % 1000, c]));
  // 멀리언을 2px 로 — 1px 선은 랩탑 화면 위로 솟아 '이상한 세로선'으로 읽혔다.
  // (유리 오른판 1px 을 덮는다 — 벽 셀맵은 유리를 못 칠하므로 rect 로 얹는다)
  rects.push(R(38, 7, 1, 25, WM));
  return rects;
}

