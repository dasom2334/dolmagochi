// 침실 v3 정적 아트 — **손작화 판**(레퍼런스 추출이 아니라 코드로 직접 그림).
// 스타일: 무테·두꺼운 색면·또렷한 실루엣 (visual-style-target).
// SCENE-RULES: 무광원 알베도 + AO 만 — 방향광 명암은 렌더 광원 레이어가 얹는다.
//
// [투사법 규칙 — 4판에서 전 소품에 통일]
//   · 눈높이 y≈22, 소실점 x≈66 (거실 바닥 소실점과 동일)
//   · y22 아래 수평면은 윗면이 보인다 — 낮을수록(가까울수록) 깊게
//     (책상 y34: 2줄 / 협탁 y36: 2줄 / 시트 y41: 2줄 / 눈높이 위 선반: 윗면 없음)
//   · VP 왼쪽 소품(책상·의자)은 **오른쪽 옆면**, 오른쪽 소품(침대·선풍기)은 **왼쪽**이 보인다
//   · 뒷다리는 앞다리보다 짧게 보인다(내려다보는 깊이차)
//   · 돌출부(상판·선반·액자) 아래엔 1px AO — 입체의 증거
import { emitRows, h2 } from '../livingroom/scene/generate.js';
import { BD_GLASS } from './geom-art.js';

const R = (x, y, w, h, c) => [x, y, w, h, c];

// 목재 공통 팔레트 — 가구 세트감. 명도·채도는 거실 목가구 수준.
const WH = '#9a6f46';   // 윗면 하이라이트
const WT = '#7e5738';   // 윗면
const WM = '#5e3f28';   // 몸통
const WD = '#402a1a';   // 어두운 면
const WX = '#2a1b10';   // 가장 깊은 그늘
const AO = '#2b2334';   // 돌출부 아래 차폐 그늘(보라 계열 — 벽·바닥과 동화)

// ── 벽 한 장 — 유리 구멍만 뚫림. 창틀은 레퍼런스처럼 **웜 우드** ──
function wall() {
  const W = 128, H = 49;
  const glass = new Set();
  for (const [x0, y0, x1, y1] of BD_GLASS)
    for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) glass.add(y * 1000 + x);
  const cell = new Map();
  const put = (x, y, c) => {
    if (y < 0 || y >= H || x < 0 || x >= W || glass.has(y * 1000 + x)) return;
    cell.set(y * 1000 + x, c);
  };
  // 바탕 — 미세 노이즈만
  for (let y = 0; y < H; y++)
    for (let x = 0; x < W; x++) {
      const r = h2(x, y, 200);
      put(x, y, r < 8 ? '#332e40' : r > 93 ? '#423c54' : '#3a3448');
    }
  // 걸레받이 — 윗단 밝고 아래 어둡게(두께)
  for (let x = 0; x < W; x++) { put(x, 47, '#4b4360'); put(x, 48, '#2b2637'); }
  // 창틀(웜 우드, 레퍼런스) — 유리(22..54 × 7..31) 둘레.
  //   바깥면 WT → 유리쪽 안단(리빌)은 WD 로 파인다. 격자(멀리언 x37·가로살 y18)는
  //   유리 틈이 1px 라 1px — 대신 같은 WM 톤으로 통일해 격자가 어긋나 보이지 않게.
  for (let x = 19; x <= 57; x++) { put(x, 5, WH); put(x, 6, WD); }
  for (let y = 5; y <= 31; y++) {
    put(19, y, WT); put(20, y, WM); put(21, y, WD);        // 왼 기둥(바깥→리빌)
    put(55, y, WD); put(56, y, WM); put(57, y, WT);        // 오른 기둥(리빌→바깥)
  }
  for (let y = 7; y <= 31; y++) put(37, y, WM);            // 멀리언
  for (let x = 22; x <= 54; x++) put(x, 18, WM);           // 가로살
  // 창턱 — 아래에 있어 윗면이 보인다. 좌우로 돌출한 선반(레지)
  for (let x = 18; x <= 58; x++) put(x, 32, '#9c8b70');
  for (let x = 19; x <= 57; x++) put(x, 33, '#6e5a44');
  for (let x = 20; x <= 56; x++) put(x, 34, '#33281c');    // 턱 밑 AO
  return emitRows([...cell].map(([k, c]) => [Math.floor(k / 1000), k % 1000, c]));
}

