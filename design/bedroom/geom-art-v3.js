//   · 옆면: VP 왼쪽 소품은 오른쪽 옆면(책상 마구리), 오른쪽 소품은 왼쪽 옆면(협탁·발판)
//   · 뒷다리는 앞다리보다 짧게. 돌출부 아래 1px AO.
//   · **가구 발은 바닥 안쪽(y50~51)까지** — 거실 pullForward 처럼 바닥 위에 선다.
