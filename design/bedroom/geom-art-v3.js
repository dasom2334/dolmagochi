// ── 액자 벽 (69..101 × 7..24) — 액자 6개 (부츠선반은 벽선반과 겹쳐 제거) ──
function frames() {
  const o = [];
  const fr = (x, y, w, h, bd, art, hi) => {
    o.push(R(x, y, w, 1, bd), R(x, y + h - 1, w, 1, bd), R(x, y, 1, h, bd), R(x + w - 1, y, 1, h, bd));
    o.push(R(x + 1, y + 1, w - 2, h - 2, art));
    if (hi) o.push(R(x + 1, y + 1, w - 2, 1, hi));
  };
  fr(80, 7, 8, 6, '#7a4a30', '#4a7a8a', '#6a9aa8');
  fr(90, 9, 9, 8, '#5c3a26', '#3a5a7a', '#587a9a');
  fr(83, 15, 6, 8, '#6e4a2e', '#6a5a7a');
  fr(91, 19, 8, 5, '#7a4a30', '#4a6a5a');
  fr(99, 8, 3, 10, '#5c3a26', '#7a6a4a');
  return o;
}

