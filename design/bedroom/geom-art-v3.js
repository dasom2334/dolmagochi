// ── 벽 한 장 — 유리 구멍만 뚫림. 창틀은 웜 우드(레퍼런스) ──
function wall() {
  const W = 128, H = 49;
  const glass = new Set();
  for (const [x0, y0, x1, y1] of BD_GLASS)
    for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) glass.add(y * 1000 + x);
  const cell = new Map();
  const put = (x, y, c) => {
    if (y < 0 || y >= H || x < 0 || x >= W || glass.has(y * 1000 + x)) return;
    cell.set(y * 1000 + x, c);
  };
  for (let y = 0; y < H; y++)
    for (let x = 0; x < W; x++) {
      const r = h2(x, y, 200);
      put(x, y, r < 8 ? '#332e40' : r > 93 ? '#423c54' : '#3a3448');
    }
  for (let x = 0; x < W; x++) { put(x, 47, '#4b4360'); put(x, 48, '#2b2637'); }
  // 창틀(웜 우드) — 리빌(유리쪽 안단)은 어둡게, 격자는 WM 톤 통일
  for (let x = 19; x <= 57; x++) { put(x, 5, WH); put(x, 6, WD); }
  for (let y = 5; y <= 31; y++) {
    put(19, y, WT); put(20, y, WM); put(21, y, WD);
    put(55, y, WD); put(56, y, WM); put(57, y, WT);
  }
  for (let y = 7; y <= 31; y++) put(37, y, WM);
  for (let x = 22; x <= 54; x++) put(x, 18, WM);
  // 창턱 — 아래라 윗면이 보인다
  for (let x = 18; x <= 58; x++) put(x, 32, '#9c8b70');
  for (let x = 19; x <= 57; x++) put(x, 33, '#6e5a44');
  for (let x = 20; x <= 56; x++) put(x, 34, '#33281c');
  return emitRows([...cell].map(([k, c]) => [Math.floor(k / 1000), k % 1000, c]));
}

