// 침실 v3 정적 아트 — **손작화 판**(레퍼런스 추출이 아니라 코드로 직접 그림).
// 스타일 목표: 무테·두꺼운 색면·또렷한 실루엣 (visual-style-target).
// SCENE-RULES 준수: 무광원 알베도 + AO 만 — 명암·창빛은 렌더 광원 레이어가 얹는다.
// 배치는 추출판(geom-art.js) bbox 기준 — 접지그림자·돌 자리·스탠드가 그대로 맞는다.
//
// [2판 수정] 모순 정리:
//   · 의자: 회색 패널(모니터로 읽힘) → 책상과 같은 나무 의자(등받이 살·시트·다리)
//   · 벽선반: 창 유리 침범 + 부츠선반과 겹침 → 창 오른쪽(x58~)으로, 부츠선반 제거
//   · 책상 위 물건: 화분·모니터가 상판 아래로 가라앉음 → 상판 3단 두께 위에 얹음
//   · 침대 발판: 2px 조각 → 바닥까지 닿는 판
//   · 창틀: 1px 선 → 거실처럼 두께(3px 기둥·2px 상단) 있는 틀
//   · 나무 가구(책상·의자·협탁·선반·액자)는 같은 목재 팔레트 = 세트감
import { emitRows, h2 } from '../livingroom/scene/generate.js';
import { BD_GLASS } from './geom-art.js';

const R = (x, y, w, h, c) => [x, y, w, h, c];

// 목재 공통 팔레트 — 방 안 나무 가구를 한 세트로 묶는다.
// 명도·채도는 거실 목가구(--wd*) 수준으로 눌러 방 전체 명암과 맞춘다.
const WH = '#9a6f46';   // 윗면 하이라이트
const WT = '#7e5738';   // 윗면
const WM = '#5e3f28';   // 몸통
const WD = '#402a1a';   // 어두운 면
const WX = '#2a1b10';   // 가장 깊은 그늘

// ── 벽 한 장 — 유리 구멍만 뚫림. 창틀(두께)·창턱·걸레받이 포함 ──
function wall() {
  const W = 128, H = 49;
  const glass = new Set();
  for (const [x0, y0, x1, y1] of BD_GLASS)
    for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) glass.add(y * 1000 + x);
  const cell = new Map();
  const put = (x, y, c) => {
    if (y < 0 || y >= H || x < 0 || x >= W || glass.has(y * 1000 + x)) return;
    cell.set(y * 1000 + x, c);
  };
  // 바탕 — 미세 노이즈만 (디테일 뭉갬 유지)
  for (let y = 0; y < H; y++)
    for (let x = 0; x < W; x++) {
      const r = h2(x, y, 200);
      put(x, y, r < 8 ? '#332e40' : r > 93 ? '#423c54' : '#3a3448');
    }
  // 걸레받이
  for (let x = 0; x < W; x++) { put(x, 47, '#4b4360'); put(x, 48, '#2b2637'); }
  // 창틀 — 유리(22..54 × 7..31) 둘레. 기둥 3px·상단 2px, 유리쪽 안단은 어둡게
  const F = '#575071', FL = '#6e6690', FD = '#3b3550';
  for (let x = 19; x <= 57; x++) { put(x, 5, FL); put(x, 6, F); }
  for (let y = 5; y <= 31; y++) {
    put(19, y, F); put(20, y, F); put(21, y, FD);         // 왼 기둥
    put(55, y, FD); put(56, y, F); put(57, y, F);          // 오른 기둥
    put(37, y, F);                                          // 멀리언
  }
  for (let x = 22; x <= 54; x++) put(x, 18, F);            // 가로살
  // 창턱 — 윗면 밝고 아래로 두 단
  for (let x = 18; x <= 58; x++) put(x, 32, '#7d6f9a');
  for (let x = 19; x <= 57; x++) put(x, 33, '#57496b');
  for (let x = 20; x <= 56; x++) put(x, 34, '#372f4a');
  return emitRows([...cell].map(([k, c]) => [Math.floor(k / 1000), k % 1000, c]));
}

