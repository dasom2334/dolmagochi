// SCENE-RULES 준수: 무광원 알베도 + AO 만 — 명암·창빛은 렌더 광원 레이어가 얹는다.
// 배치(bbox)는 추출판(geom-art.js)과 동일 좌표 — 접지그림자·돌 자리·스탠드가 그대로 맞는다.
import { emitRows, h2 } from '../livingroom/scene/generate.js';
import { BD_GLASS } from './geom-art.js';

const R = (x, y, w, h, c) => [x, y, w, h, c];

// ── 벽 한 장 — 유리 구멍만 뚫림. 창틀·창턱·걸레받이 포함 ──
function wall() {
  const W = 128, H = 49;
  const glass = new Set();
  for (const [x0, y0, x1, y1] of BD_GLASS)
    for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) glass.add(y * 1000 + x);
  const cell = new Map();
  const put = (x, y, c) => {
    if (y < 0 || y >= H || x < 0 || x >= W || glass.has(y * 1000 + x)) return;
    cell.set(y * 1000 + x, c);
  };
  // 바탕 — 미세 노이즈만(디테일 뭉갬 유지)
  for (let y = 0; y < H; y++)
    for (let x = 0; x < W; x++) {
      const r = h2(x, y, 200);
      put(x, y, r < 8 ? '#332e40' : r > 93 ? '#423c54' : '#3a3448');
    }
  // 걸레받이
  for (let x = 0; x < W; x++) { put(x, 47, '#4b4360'); put(x, 48, '#2b2637'); }
  // 창틀 — 유리(22..54 × 7..31) 둘레 + 멀리언(x37) + 가로살(y18)
  const F = '#4e4266', FL = '#635488';
  for (let x = 21; x <= 55; x++) { put(x, 6, FL); put(x, 18, F); }
  for (let y = 6; y <= 31; y++) { put(21, y, F); put(37, y, F); put(55, y, F); }
  // 창턱 — 윗면 밝고 아래로 한 단
  for (let x = 19; x <= 57; x++) put(x, 32, '#7d6f9a');
  for (let x = 20; x <= 56; x++) put(x, 33, '#57496b');
  for (let x = 21; x <= 55; x++) put(x, 34, '#372f4a');
  return emitRows([...cell].map(([k, c]) => [Math.floor(k / 1000), k % 1000, c]));
}

