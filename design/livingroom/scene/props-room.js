/** 문자 격자 → rect. 가로 런 병합까지 여기서 한다 */
export function buildRoomProps() {
  const out = {};
  for (const [id, [ox, oy, art, map]] of Object.entries(ROOM_PROPS)) {
    const rects = [];
    art.forEach((row, j) => {
      let i = 0;
      while (i < row.length) {
        const ch = row[i];
        if (ch === '.') { i++; continue; }
        let k = i;
        while (k + 1 < row.length && row[k + 1] === ch) k++;
        const slot = map[ch];
        if (slot) rects.push([ox + i, oy + j, k - i + 1, 1, slot]);
        i = k + 1;
      }
    });
    out[id] = rects;
  }
  return out;
}
