// ── 붉은 법랑 **냄비** — 씬의 유일한 색 앵커(§7) ────────────────────────
// 1차는 배부른 몸통 + 주둥이 + 한쪽 손잡이라 통째로 **주전자**로 읽혔다.
// 게임 품목은 냄비다("뭔가를 끓일 냄비", shop.json `pot`).
// 냄비로 읽히게 하는 것 셋 — 셋 다 있어야 한다:
//   1) 주둥이가 **없다**  2) 손잡이가 양쪽에 **둘**(귀)  3) 뚜껑 챙이 몸통보다 넓다
